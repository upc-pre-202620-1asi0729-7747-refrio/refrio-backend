CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 first_name VARCHAR(120) NOT NULL,
 last_name VARCHAR(120) NOT NULL,
 role VARCHAR(32) NOT NULL,
 subscription_plan VARCHAR(80) NOT NULL,
 sede VARCHAR(160) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE resource_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 resource VARCHAR(80) NOT NULL,
 external_id VARCHAR(150) NOT NULL,
 payload TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT ux_resource_external UNIQUE (resource, external_id)
);
CREATE INDEX idx_resource_name ON resource_records(resource);
CREATE TABLE operation_mutex (
 id INTEGER PRIMARY KEY,
 CONSTRAINT ck_mutex_one CHECK (id = 1)
);
